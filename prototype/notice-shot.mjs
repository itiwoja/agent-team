import { chromium } from "playwright";
const out = "shots/notice/";
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await p.goto("http://localhost:5176/");
await p.waitForSelector(".entrance", { timeout: 60000 });
await p.fill("#ask-input", "競合の値段を調べて、表にして");
await p.click('button[aria-label="頼む"]');
await p.waitForTimeout(4000);
await p.screenshot({ path: out + "0-generating.png" });
const t0 = Date.now();
await p.waitForSelector(".notice", { timeout: 540000 });
console.log("notice after", Math.round((Date.now() - t0) / 1000), "s");
await p.waitForTimeout(600);
await p.screenshot({ path: out + "1-toast.png" });
await p.click(".notice-main");
await p.waitForTimeout(500);
await p.screenshot({ path: out + "2-sheet.png" });
console.log(await p.innerText(".notice-sheet"));
await p.click("text=くわしく");
await p.waitForSelector(".report-card", { timeout: 20000 });
await p.waitForTimeout(800);
await p.screenshot({ path: out + "3-askpage.png" });
await b.close();
